package com.softserve.academy.module1;

/**
 * This class demonstrates the use of special escape characters in Java strings.
 * It includes examples of how to use tabs, backslashes, quotes, new lines, and carriage returns.
 */
class Example {
    /**
     * The main method is the entry point of the program.
     * It demonstrates the use of various escape characters in Java strings.
     * @param args
     */
    public static void main(String[] args) {
        // Using special escape characters
        System.out.println("This is a tab:\tTabbed text");
        System.out.println("This is a backslash: \\");
        System.out.println("This is a double quote: \"Quoted text\"");
        System.out.println("This is a single quote: \'Single quoted text\'");
        System.out.println("This is a new line:\nNew line text");
        System.out.println("This is a carriage return:\rCarriage return text");
    }
}

